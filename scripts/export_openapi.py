"""Export the FastAPI contract and dictionary case folding without starting a server."""

import json
import sys
import argparse
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.main import create_app  # noqa: E402

target = ROOT / "docs" / "generated" / "openapi.json"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
arguments = parser.parse_args()
schema = create_app().openapi()
folding_target = ROOT / "frontend" / "src" / "generated" / "dictionary-case-folding.ts"
folding = {chr(code): chr(code).casefold() for code in range(sys.maxunicode + 1) if chr(code).casefold() != chr(code)}
folding_source = (
    f"// Generated by scripts/export_openapi.py with Unicode {unicodedata.unidata_version}; do not edit.\n"
    "export const dictionaryCaseFolding: Readonly<Record<string, string>> = "
    + json.dumps(folding, ensure_ascii=True, separators=(",", ":")) + ";\n"
)
if arguments.check:
    if not target.exists() or json.loads(target.read_text()) != schema:
        sys.exit("OpenAPI is stale. Run cd frontend && npm run generate:api.")
    print("OpenAPI matches FastAPI models")
    if not folding_target.exists() or folding_target.read_text() != folding_source:
        sys.exit("Dictionary case folding is stale. Run cd frontend && npm run generate:api.")
    print("Dictionary case folding matches backend Python")
    sys.exit(0)
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(json.dumps(schema, ensure_ascii=False, indent=2) + "\n")
print(target.relative_to(ROOT))
folding_target.parent.mkdir(parents=True, exist_ok=True)
folding_target.write_text(folding_source)
print(folding_target.relative_to(ROOT))
